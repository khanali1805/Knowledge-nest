export function createThemeFromNiche(
  niche: ThemeNiche,
  name?: string,
): ThemeConfiguration {
  const preset =
    themePresets.find((theme) => theme.niche === niche) ??
    themePresets.find((theme) => theme.niche === "general")!;
  const timestamp = new Date().toISOString();
  return {
    ...structuredClone(preset),
    id: `${niche}-${Date.now()}`,
    name: name?.trim() || preset.name,
    isActive: false,
    version: 1,
    createdAt: timestamp,
    updatedAt: timestamp,
  };
}
