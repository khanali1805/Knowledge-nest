function createPreset(niche: ThemeNiche, name: string): ThemeConfiguration {
  const timestamp = new Date().toISOString();
  return {
    id: `${niche}-preset`,
    name,
    niche,
    layout: layouts[niche] ?? "magazine",
    version: 1,
    isActive: niche === "general",
    colours: palettes[niche],
    typography: {
      headingFont: "Inter",
      bodyFont: "Inter",
      headingWeight: 700,
      bodyWeight: 400,
    },
    sections: defaultSections.map((section) => ({ ...section })),
    navigation: [...navigationByNiche[niche]],
    createdAt: timestamp,
    updatedAt: timestamp,
  };
}
